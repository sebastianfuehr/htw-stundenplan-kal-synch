/**
 * Re-downloads the test fixtures from LSF.
 *
 * Run this periodically (a weekly CI job that opens a PR works well): the diff *is* the
 * notification that LSF changed its markup. Everything else in this project is tested against
 * these files, so a surprising diff here is the earliest possible warning.
 *
 *   node scripts/refresh-fixtures.mjs
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const BASE = 'https://lsf.htw-berlin.de/qisserver/rds';
// Kontaktadresse aus der Umgebung, damit hier nicht die Adresse einer Person steht, die
// mit dem Lauf nichts zu tun hat: OPERATOR_EMAIL=... node scripts/refresh-fixtures.mjs
const CONTACT = (process.env.OPERATOR_EMAIL ?? '').trim();
const UA = `HTW-Stundenplan-ICS/1.0 (fixture refresh${CONTACT === '' ? '' : `; ${CONTACT}`})`;
const DIR = fileURLToPath(new URL('../test/fixtures/', import.meta.url));

const plan = (sg, from, to, extra) =>
  `${BASE}?${new URLSearchParams({
    state: 'wplan', 'k_abstgv.abstgvnr': sg,
    'r_zuordabstgv.semvonint': String(from), 'r_zuordabstgv.sembisint': String(to),
    act: 'stg', pool: 'stg', 'P.vx': 'lang', 'P.subc': 'plan', ...extra,
  })}`;

const list = (sg, from, to) => plan(sg, from, to, { show: 'liste' });
const grid = (sg, from, to, week) => plan(sg, from, to, { show: 'plan', week });

/** Each entry notes *why* it is a fixture, so nobody prunes the awkward ones. */
const FIXTURES = [
  ['catalog.html', `${BASE}?${new URLSearchParams({
    state: 'change', type: '5', moduleParameter: 'abstgvSearch', nextdir: 'change',
    next: 'search.vm', subdir: 'stg', purge: 'n', 'k_abstgv.dtxt': '', search_Studiengang: 'Auswahl',
  })}`, 'all 94 Studiengänge'],
  ['list-345-1-8.html', list(345, 1, 8), 'mixed group conventions; Block rows with "keine Angabe"'],
  ['list-345-3-3.html', list(345, 3, 3), 'weekly rules with rooms'],
  ['list-350-1-8.html', list(350, 1, 8), 'Game Design: no rooms, "Termin" group heading'],
  ['grid-345-3-42_2026.html', grid(345, 3, 3, '42_2026'), 'a normal lecture week'],
  ['grid-345-3-52_2026.html', grid(345, 3, 3, '52_2026'), 'partially lecture-free week'],
  ['grid-345-3-53_2026.html', grid(345, 3, 3, '53_2026'), 'entirely lecture-free week'],
  ['grid-345-3-41_2027.html', grid(345, 3, 3, '41_2027'), 'week with no plan data: 200 OK, no header dates'],
  ['grid-345-1-8-41_2026.html', grid(345, 1, 8, '41_2026'), 'up to 10 courses stacked in one cell'],
  ['grid-345-1-8-7_2027.html', grid(345, 1, 8, '7_2027'), 'Block events in the exam period'],
  ['grid-350-3-42_2026.html', grid(350, 3, 3, '42_2026'), 'Game Design week, rooms unset'],
];

/**
 * Strips the bits of every LSF response that change on each request: the load balancer's node
 * and thread names. Without this the weekly refresh produces a diff every single time and the
 * drift alarm becomes noise nobody reads.
 */
function normalize(html) {
  return html
    .replace(/using thread [^\s"]+/g, 'using thread THREAD')
    .replace(/Generated by node "[^"]*" in cluster "[^"]*"/g, 'Generated by node "NODE" in cluster "CLUSTER"')
    .replace(/Generiert von Knoten [^\s<]+/g, 'Generiert von Knoten NODE')
    .replace(/im Cluster [^\s<]+/g, 'im Cluster CLUSTER');
}

for (const [name, url, why] of FIXTURES) {
  const res = await fetch(url, { headers: { 'User-Agent': UA }, redirect: 'follow' });
  if (!res.ok) {
    console.error(`✗ ${name}: HTTP ${res.status}`);
    process.exitCode = 1;
    continue;
  }
  const body = normalize(await res.text());
  await writeFile(DIR + name, body);
  console.log(`✓ ${name.padEnd(30)} ${String(body.length).padStart(8)} B   ${why}`);
  // Be a guest, not a load test.
  await new Promise((r) => setTimeout(r, 1000));
}
